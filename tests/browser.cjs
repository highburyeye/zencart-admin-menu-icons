/* Local fixture tests; GPL-2.0-only. Run after tests/integration.php. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
    const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox']});
    const errors = [];
    let checks = 0;
    const check = (value, label) => { assert.ok(value, label); checks++; };
    const base = 'http://127.0.0.1:8765/shop/secret-admin/index.php?cmd=admin_menu_icons';
    const artifacts = process.env.AMI_SCREENSHOT_DIR || path.join(__dirname, '.artifacts');
    fs.mkdirSync(artifacts, {recursive: true});
    const navigateAfter = async (page, action) => Promise.all([page.waitForNavigation({waitUntil: 'networkidle'}), action()]);
    try {
        const admin = await browser.newContext({viewport: {width: 1280, height: 960}});
        const page = await admin.newPage();
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(base + '&user=1', {waitUntil: 'networkidle'});
        check(await page.locator('h1').textContent() === 'Admin Menu Icons & Favourites', 'settings page renders');
        check(await page.locator('.ami-menu-entry').count() === 8, 'all registered dropdown entries decorated');
        check(await page.locator('.dropdown-toggle.ami-menu-entry').count() === 0, 'top-level headings untouched');
        await page.locator('a.dropdown-toggle').filter({hasText: 'Customers'}).click();
        const xs = await page.locator('.ami-menu-entry[data-ami-key="customers"] .ami-menu-text, .ami-menu-entry[data-ami-key="orders"] .ami-menu-text').evaluateAll(nodes => nodes.map(n => n.getBoundingClientRect().x));
        check(xs.length === 2 && Math.abs(xs[0] - xs[1]) < .5, 'dropdown labels line up');
        await page.locator('a.dropdown-toggle').filter({hasText: 'Customers'}).click();
        const fav = page.locator('#ami-row-orders .ami-switch');
        await fav.click();
        await page.waitForFunction(() => document.querySelector('#ami-row-orders .ami-switch').getAttribute('aria-checked') === 'true');
        check(await page.locator('.ami-menu-entry[data-ami-key="orders"]').evaluate(n => n.classList.contains('ami-is-favourite')), 'favourite updates live menu');
        await page.reload({waitUntil: 'networkidle'});
        check(await fav.getAttribute('aria-checked') === 'true', 'favourite survives reload');
        await page.locator('#ami-only-favourites').check();
        check(await page.locator('.ami-row:visible').count() === 1, 'favourites-only filter');
        await page.locator('#ami-only-favourites').uncheck();
        await page.locator('#ami-search').fill('Third-party');
        check(await page.locator('.ami-row:visible').count() === 1, 'entry search');
        await page.locator('#ami-search').fill('');
        await page.locator('#ami-row-orders .ami-change').click();
        check(await page.locator('#ami-picker').evaluate(n => n.open), 'picker opens');
        await page.locator('#ami-icon-search').fill('truck');
        check(await page.locator('.ami-icon-option[data-kind="fa"]:visible').count() === 1, 'built-in icon search');
        await page.screenshot({path: path.join(artifacts, 'picker.png')});
        await navigateAfter(page, () => page.locator('.ami-pick[data-kind="fa"][data-value="truck"]').click());
        check(await page.locator('.ami-menu-entry[data-ami-key="orders"] .fa-truck').count() === 1, 'replacement icon');
        await page.locator('#ami-row-orders .ami-change').click();
        await navigateAfter(page, () => page.locator('.ami-pick[data-kind="none"]').click());
        check(await page.locator('.ami-menu-entry[data-ami-key="orders"] .ami-icon-slot > *').count() === 0, 'no icon keeps empty slot');
        await page.locator('a.dropdown-toggle').filter({hasText: 'Customers'}).click();
        const mixed = await page.locator('.ami-menu-entry[data-ami-key="customers"] .ami-menu-text, .ami-menu-entry[data-ami-key="orders"] .ami-menu-text').evaluateAll(nodes => nodes.map(n => n.getBoundingClientRect().x));
        check(Math.abs(mixed[0] - mixed[1]) < .5, 'mixed icon and blank alignment');
        await page.screenshot({path: path.join(artifacts, 'dropdown-alignment.png')});
        await page.locator('a.dropdown-toggle').filter({hasText: 'Customers'}).click();
        await page.locator('#ami-row-configImages .ami-change').click();
        await navigateAfter(page, () => page.locator('.ami-pick[data-kind="fa"][data-value="image"]').click());
        check(await page.locator('.ami-menu-entry[data-ami-key="configImages"] .fa-image').count() === 1, 'parameter-specific configuration entry');
        check(await page.locator('.ami-menu-entry[data-ami-key="configMyStore"] .ami-icon-slot > *').count() === 0, 'other configuration group unaffected');
        await page.locator('#ami-row-orders .ami-change').click();
        const label = 'NULL & "clinic" <demo> — 目 :data:';
        await page.locator('#ami-upload-label').fill(label);
        await page.locator('input[name="ami_file"]').setInputFiles(path.join(__dirname, 'icon-test.png'));
        await navigateAfter(page, () => page.locator('#ami-upload-form button[type="submit"]').click());
        check((await page.locator('#ami-row-orders .ami-icon-name').textContent()).includes(label), 'upload name stays literal through core sanitizer and SQL binding');
        check(await page.locator('.ami-menu-entry[data-ami-key="orders"] img').evaluate(img => img.complete && img.naturalWidth === 64 && img.naturalHeight === 32), 'uploaded raster converted and displayed');
        check(await page.locator('.ami-upload-card button').isDisabled(), 'assigned upload protected from deletion');
        await page.screenshot({path: path.join(artifacts, 'settings-desktop.png'), fullPage: true});

        const staff = await browser.newContext({viewport: {width: 1280, height: 960}});
        const staffPage = await staff.newPage();
        staffPage.on('pageerror', error => errors.push(error.message));
        await staffPage.goto(base + '&user=2', {waitUntil: 'networkidle'});
        check(await staffPage.locator('.ami-change').count() === 0, 'staff cannot edit shared icons');
        check(await staffPage.locator('#ami-row-categoriesProductListing').count() === 0, 'restricted pages absent');
        check(await staffPage.locator('.ami-menu-entry[data-ami-key="orders"] img').count() === 1, 'shared upload visible to staff');
        check(await staffPage.locator('#ami-row-orders .ami-switch').getAttribute('aria-checked') === 'false', 'superadmin favourite not copied to staff');
        await staffPage.locator('#ami-row-orders .ami-switch').click();
        await staffPage.waitForFunction(() => document.querySelector('#ami-row-orders .ami-switch').getAttribute('aria-checked') === 'true');
        await fav.click();
        await page.waitForFunction(() => document.querySelector('#ami-row-orders .ami-switch').getAttribute('aria-checked') === 'false');
        await staffPage.reload({waitUntil: 'networkidle'});
        check(await staffPage.locator('#ami-row-orders .ami-switch').getAttribute('aria-checked') === 'true', 'users can choose independently');
        const forbidden = await staff.request.post(base, {form: {ami_response: 'json', securityToken: 'ami-test-csrf-token', ami_action: 'save_icon', ami_page: 'orders', ami_kind: 'none'}});
        check(forbidden.status() === 403, 'forged shared-icon request rejected');
        const csrf = await staff.request.post(base, {form: {ami_response: 'json', securityToken: 'wrong', ami_action: 'favourite', ami_page: 'orders', ami_favourite: '0'}});
        check(csrf.status() === 403, 'CSRF request rejected');
        check((await csrf.json()).ok === false, 'CSRF error is structured');
        await page.setViewportSize({width: 390, height: 844});
        await page.screenshot({path: path.join(artifacts, 'settings-mobile.png'), fullPage: true});
        check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile has no whole-page horizontal overflow');
        check(errors.length === 0, 'no JavaScript errors: ' + errors.join('; '));
        console.log('PASS: ' + checks + ' browser checks, Chromium local fixture');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
